#!/usr/bin/env node
// Renders the four mock screens in eval/fixtures/text/*.html (fake data: a purchase order, an email, a chat,
// an invoice) to PNG with headless Chrome and writes the exact pixel boxes of the elements marked
// data-t="..." to eval/fixtures/text/truth.mjs. The boxes come from the page itself, not from eyeballing.
// Developer tool (macOS Chrome path); the PNGs and truth.mjs are committed, so the evaluation does not need it.
//
//   node scripts/make-text-fixtures.mjs                  all screens
//   node scripts/make-text-fixtures.mjs t5-projects.html  only the named screens (their boxes are merged into truth.mjs)

import { spawn } from "node:child_process";
import { mkdtempSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = resolve(root, "eval/fixtures/text");
const CHROME = process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const port = 9344;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const chrome = spawn(CHROME, [`--remote-debugging-port=${port}`, `--user-data-dir=${mkdtempSync(join(tmpdir(), "pyosi-fx-"))}`, "--headless=new", "--hide-scrollbars", "--no-first-run", "about:blank"], { stdio: "ignore" });
let target;
for (let i = 0; i < 40 && !target; i++) {
  try { target = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find((t) => t.type === "page"); } catch {}
  if (!target) await sleep(250);
}
const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0;
const pending = new Map();
ws.onmessage = (m) => { const d = JSON.parse(m.data); if (d.id && pending.has(d.id)) { pending.get(d.id)(d); pending.delete(d.id); } };
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });

const only = process.argv.slice(2);
const truth = only.length ? { ...(await import(join(dir, "truth.mjs"))).TEXT_TRUTH } : {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".html") && (!only.length || only.includes(f))).sort()) {
  const name = file.replace(/\.html$/, "");
  await send("Emulation.setDeviceMetricsOverride", { width: 1200, height: 800, deviceScaleFactor: 1, mobile: false });
  await send("Page.navigate", { url: `file://${join(dir, file)}` });
  await sleep(1200);
  const r = await send("Runtime.evaluate", {
    returnByValue: true,
    expression: `JSON.stringify({h: Math.ceil(document.documentElement.scrollHeight), boxes: Object.fromEntries([...document.querySelectorAll('[data-t]')].map(e => { const b = e.getBoundingClientRect(); return [e.dataset.t, [Math.round(b.left + scrollX), Math.round(b.top + scrollY), Math.round(b.right + scrollX), Math.round(b.bottom + scrollY)]]; }))})`,
  });
  const { h, boxes } = JSON.parse(r.result.result.value);
  const height = Math.max(h, 500);
  await send("Emulation.setDeviceMetricsOverride", { width: 1200, height, deviceScaleFactor: 1, mobile: false });
  await sleep(300);
  const shot = await send("Page.captureScreenshot", { format: "png", clip: { x: 0, y: 0, width: 1200, height, scale: 1 } });
  writeFileSync(join(dir, `${name}.png`), Buffer.from(shot.result.data, "base64"));
  Object.assign(truth, boxes);
  console.log(`${name}.png  1200x${height}  ${JSON.stringify(boxes)}`);
}
writeFileSync(join(dir, "truth.mjs"), `// Generated by scripts/make-text-fixtures.mjs: pixel boxes [x0, y0, x1, y1] of the elements marked data-t in the mock screens.\nexport const TEXT_TRUTH = ${JSON.stringify(truth, null, 2)};\n`);
ws.close();
chrome.kill();
